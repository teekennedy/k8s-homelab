// Lints every YAML file in the repo with yamllint.
package main

import (
	"context"
	"errors"
	"fmt"

	"dagger/yaml/internal/dagger"
)

// Yaml runs yamllint over the repo.
type Yaml struct {
	// +private
	Container *dagger.Container
}

// Lints every YAML file in the repo.
func New(
	// Container to run in. It needs yamllint. dagger.toml wires in
	// devenv\'s toolchain.
	container *dagger.Container,
) *Yaml {
	return &Yaml{Container: container}
}

// Lint runs yamllint in strict mode against .yamllint.yaml.
//
// This replaces the yamllint git hook that used to live in devenv.nix, and it
// is a real gate: the previous implementation caught the exec error and
// returned success with a "completed with warnings" string, so `dagger check`
// could never fail on YAML while the local hook blocked the commit.
// +check
func (m *Yaml) Lint(ctx context.Context,
	// +defaultPath="/"
	// .pre-commit-config.yaml and .devenv are generated by devenv and
	// gitignored. The config file is a symlink into the nix store, which
	// resolves in a local shell but dangles once copied into a container, so
	// yamllint fails on it with ENOENT rather than a lint error.
	// +ignore=["*", "!**/*.yaml", "!**/*.yml", "!.yamllint.yaml", ".pre-commit-config.yaml", ".devenv*", ".devenv/**", "k8s/**/mixins/vendor/**"]
	source *dagger.Directory,
	// +optional
	paths []string,
) error {
	args := []string{"yamllint", "--config-file", ".yamllint.yaml", "--format", "parsable", "--strict"}
	if len(paths) > 0 {
		args = append(args, paths...)
	} else {
		args = append(args, ".")
	}
	container := m.Container

	out, err := container.
		WithMountedDirectory("/src", source).
		WithWorkdir("/src").
		WithExec(args).
		Stdout(ctx)
	if err != nil {
		if execErr, ok := errors.AsType[*dagger.ExecError](err); ok {
			return fmt.Errorf("yamllint failed:\n%s%s", execErr.Stdout, execErr.Stderr)
		}
		return fmt.Errorf("yamllint failed: %w\n%s", err, out)
	}

	return nil
}
